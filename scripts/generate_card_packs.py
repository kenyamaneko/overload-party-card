#!/usr/bin/env python3
"""YAML のカードパック定義から、初期投入 SQL を生成する。

    python3 scripts/generate_card_packs.py
"""

from pathlib import Path

from generation_io import format_sql_boolean, load_yaml_file, quote_sql_string, write_lines_file

ROOT = Path(__file__).resolve().parent.parent
YAML_IN = ROOT / "data" / "card_packs.yaml"
SEED_OUT = ROOT / "db" / "seed" / "card_packs_seed.sql"

DESCRIPTION_WHEN_OMITTED = ""
IS_ACTIVE_WHEN_OMITTED = True


def load_packs() -> list[dict]:
    """パック定義を読み込む。

    Raises:
        FileNotFoundError: パック定義のファイルが無いとき。
        ValueError: 最上位に packs が無いとき。
    """
    data = load_yaml_file(YAML_IN)
    if not isinstance(data, dict) or "packs" not in data:
        raise ValueError(f"{YAML_IN}: top-level 'packs' key is required")
    return data["packs"]


def validate_packs(packs: list[dict]) -> None:
    """パック定義を検証する。

    Raises:
        ValueError: 最初に見つけた誤りを示す。
    """
    seen_pack_ids: set[str] = set()
    for pack in packs:
        pack_id = pack.get("pack_id")
        if not isinstance(pack_id, str) or not pack_id:
            raise ValueError(f"pack_id must be a non-empty string: {pack!r}")
        if pack_id in seen_pack_ids:
            raise ValueError(f"duplicate pack_id: {pack_id}")
        seen_pack_ids.add(pack_id)

        cards = pack.get("cards")
        if not isinstance(cards, list) or not cards:
            raise ValueError(f"{pack_id}: cards must be a non-empty list of {{card_id, copies}} entries")
        seen_card_ids: set[str] = set()
        for entry in cards:
            if not isinstance(entry, dict):
                raise ValueError(f"{pack_id}: cards entries must be mappings, got {entry!r}")
            card_id = entry.get("card_id")
            copies = entry.get("copies")
            if not isinstance(card_id, str) or not card_id:
                raise ValueError(f"{pack_id}: card_id must be a non-empty string, got {card_id!r}")
            if card_id in seen_card_ids:
                raise ValueError(f"{pack_id}: duplicate card_id {card_id}")
            seen_card_ids.add(card_id)
            if not isinstance(copies, int) or copies <= 0:
                raise ValueError(
                    f"{pack_id}/{card_id}: copies must be a positive int, got {copies!r}"
                )


def build_card_packs_seed_lines(packs: list[dict]) -> list[str]:
    """パックの初期投入 SQL を、行のリストとして組み立てる。"""
    lines = ["-- Auto-generated by scripts/generate_card_packs.py. DO NOT EDIT.", ""]

    pack_rows = []
    for pack in packs:
        description = pack.get("description") or DESCRIPTION_WHEN_OMITTED
        is_active = pack.get("is_active", IS_ACTIVE_WHEN_OMITTED)
        pack_rows.append(
            f"  ({quote_sql_string(pack['pack_id'])}, {quote_sql_string(description)}, "
            f"{format_sql_boolean(is_active)})"
        )

    lines.append("INSERT INTO card.card_pack (pack_id, description, is_active)")
    lines.append("VALUES")
    lines.append(",\n".join(pack_rows))
    lines.append("ON CONFLICT (pack_id) DO UPDATE SET")
    lines.append("  description = EXCLUDED.description,")
    lines.append("  is_active   = EXCLUDED.is_active;")
    lines.append("")

    pack_card_rows = []
    pack_ids = []
    for pack in packs:
        pack_ids.append(pack["pack_id"])
        for entry in pack["cards"]:
            pack_card_rows.append(
                f"  ({quote_sql_string(pack['pack_id'])}, {quote_sql_string(entry['card_id'])}, {entry['copies']})"
            )

    pack_id_list = ", ".join(quote_sql_string(pack_id) for pack_id in pack_ids)
    lines.append(f"DELETE FROM card.card_pack_cards WHERE pack_id IN ({pack_id_list});")
    lines.append("")
    lines.append("INSERT INTO card.card_pack_cards (pack_id, card_id, copies)")
    lines.append("VALUES")
    lines.append(",\n".join(pack_card_rows) + ";")
    return lines


def main() -> None:
    """パック定義を検証し、初期投入 SQL を生成する。"""
    packs = load_packs()
    validate_packs(packs)
    write_lines_file(SEED_OUT, build_card_packs_seed_lines(packs))
    total_cards = sum(len(pack["cards"]) for pack in packs)
    print(f"Wrote {SEED_OUT.relative_to(ROOT)} ({len(packs)} packs, {total_cards} pack-card rows)")


if __name__ == "__main__":
    main()
